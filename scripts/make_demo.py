"""Write a synthetic demo family: family.json plus 23andMe-format raw files, for trying the pipeline and testing it.

Usage: python3 -I scripts/make_demo.py [outdir]      (default: <repo>/demo-data)
Then:  DNA_DATA=<outdir> ./run_all.sh --quick

Nobody in it is real. Founders (the virtual maternal grandfather, the maternal grandmother and the father) get random
haplotypes; the mother is their child and self (male) and a sister are the parents' children, with Poisson crossovers
per meiosis, X passed father -> daughter only, Y father -> son, mtDNA mother -> children. Sites:
  - ~120k background SNPs spread over chromosomes 1-22 and X with synthetic IDs (rs99...), frequencies ~ Beta(0.5, 0.5);
  - every real rsID the scripts look up, at its GRCh37 position with Ensembl's alleles (only the rsIDs are sent;
    answers are cached in <outdir>/.ensembl_cache.json), each with a modest alt frequency so some people carry it;
  - chrY and mtDNA sites (all reference) so the haplogroup steps have input.
Deterministic for a given seed and set of scripts.
"""
import bisect
import glob
import json
import math
import os
import random
import re
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dnalib import CHROM_LEN, CODE

SEED = 20260101
N_BACKGROUND = 120_000
CROSSOVER_PER_BP = 1e-8  # ~1 crossover per 100 Mb per meiosis, roughly sex-averaged
PANEL_ALT_FREQ = 0.15
NO_CALL = 0.005
ENSEMBL = "https://grch37.rest.ensembl.org/variation/homo_sapiens"
BATCH = 200
LOOKUP_CHROMS = set(CHROM_LEN) | {"Y", "MT"}

# The fictional family. Ids are deliberately not the conventional folder names, to exercise family.json.
FAMILY = {
    "people": {
        "alex": {"role": "self", "name": "Alex", "sex": "M"},
        "maya": {"role": "sibling", "name": "Maya", "sex": "F"},
        "rosa": {"role": "mother", "name": "Rosa", "sex": "F"},
        "tom": {"role": "father", "name": "Tom", "sex": "M"},
        "edith": {"role": "maternal_grandmother", "name": "Edith", "sex": "F"},
    },
    "maternal_grandfather": {"name": "Walter"},
}

# rCRS bases at well-known haplogroup-defining mtDNA positions (rCRS itself is haplogroup H2a2a1).
MT_RCRS = {73: "A", 263: "A", 750: "A", 1438: "A", 2706: "A", 3010: "G", 4216: "T", 4769: "A", 7028: "C",
           8860: "A", 9477: "G", 10398: "A", 10873: "T", 11719: "G", 12308: "A", 12705: "C", 14766: "C",
           15326: "A", 16223: "C", 16519: "T"}
Y_SITES = 1200                 # analyze.py calls a sample male above 500 Y calls
Y_RANGE = (2_700_000, 28_000_000)  # male-specific region of chrY (GRCh37), outside the PARs

HEADER = """\
# This data file generated by make_demo.py (synthetic demo data, not a real person) at: Thu Jan 01 00:00:00 2026
#
# Format follows 23andMe raw data (v5): one row per SNP, reference human assembly build 37 (GRCh37),
# genotypes on the plus strand, "--" for no-calls, one letter for hemizygous X/Y/MT calls in males.
#
# rsid\tchromosome\tposition\tgenotype
"""


# ---------------------------------------------------------------- sites
def panel_rsids():
    """Every rsID token in the analysis scripts (the panels, plus a few in comments, which do no harm)."""
    ids = set()
    for path in glob.glob(os.path.join(CODE, "scripts", "*.py")):
        if os.path.basename(path) != os.path.basename(__file__):
            ids |= set(re.findall(r"\brs\d+\b", open(path, encoding="utf-8").read()))
    return sorted(ids, key=lambda r: int(r[2:]))


def post(ids):
    body = json.dumps({"ids": ids}).encode()
    for attempt in range(6):
        try:
            req = urllib.request.Request(ENSEMBL, data=body, method="POST",
                                         headers={"Content-Type": "application/json", "Accept": "application/json"})
            with urllib.request.urlopen(req, timeout=60) as r:
                return json.load(r)
        except (urllib.error.HTTPError, urllib.error.URLError, json.JSONDecodeError, TimeoutError, OSError) as e:
            print(f"  Ensembl request failed ({e}); retrying", flush=True)
            time.sleep(2 * (attempt + 1))
    raise RuntimeError("Ensembl GRCh37 lookup failed; rerun later (answers so far are cached)")


def lookup(rsids, cache_path):
    """{rsid: {"chrom", "pos", "alleles"} or None} from Ensembl GRCh37, cached across runs."""
    cache = json.load(open(cache_path)) if os.path.exists(cache_path) else {}
    todo = [rs for rs in rsids if rs not in cache]
    for i in range(0, len(todo), BATCH):
        batch = todo[i:i + BATCH]
        print(f"Looking up {len(batch)} rsIDs on Ensembl GRCh37 ...", flush=True)
        res = post(batch)
        for key, v in res.items():  # merged rsIDs come back under the requested id or the current name
            for rs in {key, v.get("name")} & set(batch):
                maps = [m for m in v.get("mappings", []) if m.get("seq_region_name") in LOOKUP_CHROMS]
                cache[rs] = maps and {"chrom": maps[0]["seq_region_name"], "pos": maps[0]["start"],
                                      "alleles": maps[0]["allele_string"].split("/")} or None
        for rs in batch:
            cache.setdefault(rs, None)
        with open(cache_path, "w") as fh:
            json.dump(cache, fh, indent=0, sort_keys=True)
    return {rs: cache.get(rs) for rs in rsids}


def chip_alleles(alleles, rng):
    """(ref, alt) as a chip reports them: bases for SNVs, D/I for indels (D = the shorter allele)."""
    if all(len(a) == 1 and a in "ACGT" for a in alleles):
        return alleles[0], rng.choice(alleles[1:])
    ref, alt = alleles[0], rng.choice(alleles[1:])
    short = lambda a: 0 if a == "-" else len(a)
    return ("D", "I") if short(ref) < short(alt) else ("I", "D")


def make_sites(cache_path):
    """{chrom: [(pos, id, ref, alt, alt_freq)]} sorted by position."""
    rng = random.Random(SEED)
    sites = {c: [] for c in list(CHROM_LEN) + ["Y", "MT"]}
    taken = set()
    # Real panel sites first, so background sites never land on them.
    rsids = panel_rsids()
    found = lookup(rsids, cache_path)
    prng = random.Random(SEED + 1)
    missing = []
    for rs in rsids:
        hit = found.get(rs)
        if not hit or len(hit["alleles"]) < 2 or (hit["chrom"], hit["pos"]) in taken:
            missing.append(rs)
            continue
        ref, alt = chip_alleles(hit["alleles"], prng)
        sites[hit["chrom"]].append((hit["pos"], rs, ref, alt, PANEL_ALT_FREQ))
        taken.add((hit["chrom"], hit["pos"]))
    # Background: evenly spaced over the genome with a little jitter.
    total = sum(CHROM_LEN.values())
    step = total / N_BACKGROUND
    n = 0
    for chrom, length in CHROM_LEN.items():
        pos = rng.uniform(0, step)
        while pos < length:
            p = int(pos + rng.uniform(-step / 4, step / 4))
            if 0 < p <= length and (chrom, p) not in taken:
                n += 1
                ref, alt = rng.sample("ACGT", 2)
                freq = min(0.95, max(0.05, rng.betavariate(0.5, 0.5)))
                sites[chrom].append((p, f"rs{9_900_000_000 + n}", ref, alt, freq))
                taken.add((chrom, p))
            pos += step
    for i, p in enumerate(sorted(rng.sample(range(*Y_RANGE), Y_SITES))):
        ref, alt = rng.sample("ACGT", 2)
        sites["Y"].append((p, f"rs{9_910_000_000 + i + 1}", ref, alt, 0.0))
    for i, (p, b) in enumerate(sorted(MT_RCRS.items())):
        sites["MT"].append((p, f"rs{9_920_000_000 + i + 1}", b, next(c for c in "GACT" if c != b), 0.0))
    for c in sites:
        sites[c].sort()
    return sites, missing, n


# ---------------------------------------------------------------- genomes
# A genome is {chrom: (hap_a, hap_b)} of 0/1 allele lists (0 = ref); a male's X, and Y and MT, use (hap, None).
def founder(sites, sex, rng):
    g = {}
    for c, s in sites.items():
        draw = lambda: [int(rng.random() < f) for *_, f in s]
        if c in ("Y", "MT"):
            g[c] = (draw(), None) if c == "MT" or sex == "M" else None
        else:
            g[c] = (draw(), draw() if c != "X" or sex == "F" else None)
    return g


def recombine(a, b, positions, length, rng):
    """One meiotic product of haplotypes a and b: Poisson crossovers at uniform positions."""
    # Poisson count by inversion (random has no poisson sampler).
    lam, k, u = length * CROSSOVER_PER_BP, 0, rng.random()
    p = cum = math.exp(-lam)
    while u > cum:
        k += 1
        p *= lam / k
        cum += p
    cuts = sorted(bisect.bisect_left(positions, rng.uniform(0, length)) for _ in range(k))
    haps = [a, b] if rng.random() < 0.5 else [b, a]
    out, start = [], 0
    for i, cut in enumerate(cuts + [len(positions)]):
        out += haps[i % 2][start:cut]
        start = cut
    return out


def gamete(parent, parent_sex, child_sex, sites, rng):
    g = {}
    for c, s in sites.items():
        if c == "Y":
            g[c] = parent[c][0] if parent_sex == "M" and child_sex == "M" else None
        elif c == "MT":
            g[c] = parent[c][0] if parent_sex == "F" else None
        elif c == "X" and parent_sex == "M":
            g[c] = parent[c][0] if child_sex == "F" else None
        else:
            a, b = parent[c]
            g[c] = recombine(a, b, [x[0] for x in s], CHROM_LEN[c], rng)
    return g


def child(mother, father, sex, sites, rng):
    m = gamete(mother, "F", sex, sites, rng)
    f = gamete(father, "M", sex, sites, rng)
    g = {}
    for c in sites:
        if c == "Y":
            g[c] = (f[c], None) if sex == "M" else None
        elif c == "MT":
            g[c] = (m[c], None)
        elif c == "X" and sex == "M":
            g[c] = (m[c], None)
        else:
            g[c] = (m[c], f[c])
    return g


def write_raw(path, genome, sites, rng):
    with open(path, "w") as fh:
        fh.write(HEADER)
        for c, s in sites.items():
            if genome[c] is None:
                continue
            a, b = genome[c]
            for i, (pos, rs, ref, alt, _) in enumerate(s):
                al = (ref, alt)
                if rng.random() < NO_CALL:
                    gt = "--"
                elif b is None:
                    gt = al[a[i]]
                else:
                    gt = al[a[i]] + al[b[i]]
                fh.write(f"{rs}\t{c}\t{pos}\t{gt}\n")


def main():
    out = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(CODE, "demo-data"))
    os.makedirs(out, exist_ok=True)
    sites, missing, n_bg = make_sites(os.path.join(out, ".ensembl_cache.json"))
    rng = random.Random(SEED + 2)
    sex = {p: v["sex"] for p, v in FAMILY["people"].items()}
    by_role = {v["role"]: p for p, v in FAMILY["people"].items()}
    grandpa = founder(sites, "M", rng)  # virtual: never written
    for c in ("Y", "MT"):  # lineage sites stay at reference; the father's mtDNA differs from rCRS (non-H)
        grandpa[c] = grandpa[c] and ([0] * len(sites[c]), None)
    gen = {by_role["maternal_grandmother"]: founder(sites, "F", rng), by_role["father"]: founder(sites, "M", rng)}
    gen[by_role["maternal_grandmother"]]["MT"] = ([0] * len(sites["MT"]), None)
    gen[by_role["father"]]["Y"] = ([0] * len(sites["Y"]), None)
    gen[by_role["father"]]["MT"] = ([int(s[0] in (73, 263, 750, 1438, 2706, 4769, 7028, 8860, 11719, 12308, 14766,
                                                    15326, 9477)) for s in sites["MT"]], None)
    mother, father = by_role["mother"], by_role["father"]
    gen[mother] = child(gen[by_role["maternal_grandmother"]], grandpa, "F", sites, rng)
    for p, v in FAMILY["people"].items():
        if v["role"] in ("self", "sibling"):
            gen[p] = child(gen[mother], gen[father], sex[p], sites, rng)
    with open(os.path.join(out, "family.json"), "w") as fh:
        json.dump(FAMILY, fh, indent=2)
        fh.write("\n")
    for p, v in FAMILY["people"].items():
        d = os.path.join(out, "raw", p)
        os.makedirs(d, exist_ok=True)
        for old in glob.glob(os.path.join(d, "genome_*.txt")):
            os.remove(old)
        write_raw(os.path.join(d, f"genome_Demo_{v['name']}_v5_Full_20260101000000.txt"), gen[p], sites,
                  random.Random(f"{SEED}-{p}"))
    n_panel = sum(1 for s in sites.values() for x in s if not x[1].startswith("rs99"))
    print(f"Wrote {out}: {len(FAMILY['people'])} people, {n_bg} background + {n_panel} panel + "
          f"{len(sites['Y'])} chrY + {len(sites['MT'])} mtDNA sites")
    if missing:
        print(f"{len(missing)} rsIDs not placed (no GRCh37 mapping or duplicate position): {' '.join(missing)}")


if __name__ == "__main__":
    main()
